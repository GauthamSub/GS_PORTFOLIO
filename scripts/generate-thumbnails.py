"""Generate lightweight previews for raster assets referenced by the portfolio.

Requires Pillow. Originals stay untouched and remain the zoom/download targets.
Filename matching includes source strings concatenated to directory constants.
"""
from pathlib import Path
import hashlib
import json
import re
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'public' / 'assets'
OUTPUT = ASSETS / 'previews'
SOURCE = ROOT / 'src'
texts = [p.read_text(encoding='utf-8', errors='replace') for p in SOURCE.rglob('*')
         if p.suffix in {'.js', '.jsx', '.css'} and p.name != 'media.js']
source_text = '\n'.join(texts)
OUTPUT.mkdir(exist_ok=True)
mapping = {}
original_bytes = 0
preview_bytes = 0

for source in sorted(ASSETS.rglob('*')):
    if not source.is_file() or source.suffix.lower() not in {'.png', '.jpg', '.jpeg', '.webp'}:
        continue
    relative = source.relative_to(ASSETS)
    if relative.parts[0] in {'previews', 'share'} or source.name not in source_text:
        continue
    source_url = '/assets/' + relative.as_posix()
    stem = re.sub(r'[^a-z0-9]+', '-', source.stem.lower()).strip('-')
    digest = hashlib.sha256(source_url.encode()).hexdigest()[:8]
    target = OUTPUT / f'{stem}-{digest}.webp'
    with Image.open(source) as original:
        preview = ImageOps.exif_transpose(original)
        preview.thumbnail((1200, 1000), Image.Resampling.LANCZOS)
        if preview.mode not in {'RGB', 'RGBA'}:
            preview = preview.convert('RGBA' if 'transparency' in preview.info else 'RGB')
        preview.save(target, 'WEBP', quality=82, method=6)
    mapping[source_url] = '/assets/previews/' + target.name
    original_bytes += source.stat().st_size
    preview_bytes += target.stat().st_size

module = '// Generated by scripts/generate-thumbnails.py. Originals remain full-resolution targets.\n'
module += 'const previews = ' + json.dumps(mapping, ensure_ascii=False, indent=2) + '\n\n'
module += 'export const thumbnail = (src) => previews[src] || src\n'
(SOURCE / 'data' / 'media.js').write_text(module, encoding='utf-8')
print(f'{len(mapping)} previews: {original_bytes:,} source bytes -> {preview_bytes:,} preview bytes. Originals unchanged.')
